"""Convert every CSV of a folder into a C song, and write songs.h to pick one.

Usage: python3 csv_to_songs.py reference/ songs/

Each <midi name>_<index>_<track name>.csv becomes songs/song_<index>_<track name>.h
(see csv_to_song.py). songs.h includes the one selected by TRACK, which is the
<index> of the track: #define it before including songs.h.
"""
import glob, os, re, sys
from csv_to_song import read, write

def main(csv_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    tracks = []
    for source in sorted(glob.glob(os.path.join(csv_dir, '*.csv'))):
        m = re.search(r'_(\d+)_([^_].*)\.csv$', os.path.basename(source))
        if not m:
            print(f"skipping {source}: no _<index>_<track name> in its name", file=sys.stderr)
            continue
        index, name = int(m.group(1)), m.group(2)
        header = f"song_{index:02d}_{name.lower()}.h"
        write(read(source), source, os.path.join(out_dir, header), 'song', '../song.h')
        tracks.append((index, name, header))
        print(os.path.join(out_dir, header))
    with open(os.path.join(out_dir, 'songs.h'), 'w') as f:
        f.write("// Generated by script/csv_to_songs.py, do not edit by hand.\n")
        f.write("// includes the song of track TRACK, #define it before including this file.\n")
        f.write("#ifndef SONGS_H\n#define SONGS_H\n\n")
        for i, (index, name, header) in enumerate(tracks):
            f.write(f"#{'if  ' if i == 0 else 'elif'} TRACK == {index:2d} // {name}\n")
            f.write(f"#include \"{header}\"\n")
        f.write("#else\n#error \"unknown TRACK, see the list in songs.h\"\n#endif\n\n#endif\n")
    print(os.path.join(out_dir, 'songs.h'))

if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])

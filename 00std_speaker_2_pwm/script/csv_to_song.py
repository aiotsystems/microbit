"""Convert a CSV (note,frequency_hz,duration_ms) into a C song for the micro:bit.

Usage: python3 csv_to_song.py track.csv song_xxx.h [array_name]

The output defines `const note_t <array_name>[]` (type in song.h): each entry
is a (PWM period, duration in ms) pair.
"""
import csv, os, sys

PWM_CLOCK_HZ = 4_000_000   # 16 MHz / prescaler 4 (see pwm_init)
COUNTERTOP_MAX = 32767     # nRF52 PWM COUNTERTOP is 15 bits wide
DURATION_MAX_MS = 65535    # duration is stored as uint16_t
EXCERPT_LINES = 5          # CSV lines copied into the header comment

def period(freq):
    """PWM period of a frequency, raised by octaves while it does not fit COUNTERTOP."""
    if freq <= 0:
        return 0, 0
    octaves = 0
    while round(PWM_CLOCK_HZ / freq) > COUNTERTOP_MAX:
        freq *= 2; octaves += 1
    return round(PWM_CLOCK_HZ / freq), octaves

def read(path):
    """Return [(name, period, duration_ms)], consecutive silences merged, empty durations dropped."""
    notes = []
    raised = 0
    with open(path, newline='') as f:
        for row in csv.DictReader(f):
            duration = int(row['duration_ms'])
            if duration <= 0:
                continue
            p, octaves = period(float(row['frequency_hz']))
            raised += octaves > 0
            name = row['note'] if p else 'silence'
            if p == 0 and notes and notes[-1][1] == 0:
                notes[-1] = (name, 0, notes[-1][2] + duration)
            else:
                notes.append((name, p, duration))
    if raised:
        print(f"warning: {raised} note(s) too low for the PWM, raised by one or more octaves", file=sys.stderr)
    # a duration that does not fit uint16_t is split into several identical entries
    result = []
    for name, p, duration in notes:
        while duration > DURATION_MAX_MS:
            result.append((name, p, DURATION_MAX_MS)); duration -= DURATION_MAX_MS
        result.append((name, p, duration))
    return result

def write(notes, source, output, array_name):
    guard = os.path.basename(output).upper().replace('.', '_')
    total = sum(d for _, _, d in notes)
    excerpt = open(source).read().splitlines()[:EXCERPT_LINES]
    with open(output, 'w') as f:
        f.write(f"// Generated by script/csv_to_song.py, do not edit by hand.\n")
        f.write(f"// {len(notes)} notes, {total / 1000:.1f} s, from {os.path.relpath(source, os.path.dirname(output) or '.')}:\n")
        f.write("//\n")
        for line in excerpt:
            f.write(f"//   {line}\n")
        f.write("//   ...\n//\n")
        f.write(f"// each line becomes {{ period, duration_ms }} with period = {PWM_CLOCK_HZ}/frequency_hz\n")
        f.write("// (0 for a silence); consecutive silences are merged.\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n\n#include \"song.h\"\n\n")
        f.write(f"const note_t {array_name}[] = {{\n")
        f.write("    // period, duration_ms\n")
        for name, p, d in notes:
            f.write(f"    {{ {p:5d}, {d:5d} }}, // {name}\n")
        f.write("};\n\n#endif\n")

if __name__ == '__main__':
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    source, output = sys.argv[1], sys.argv[2]
    array_name = sys.argv[3] if len(sys.argv) == 4 else 'song'
    write(read(source), source, output, array_name)

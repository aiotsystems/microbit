"""Convert every CSV of a folder into a C song, and write songs.h to pick one.

Usage: python3 csv_to_songs.py reference/ songs/

Each <midi name>_<index>_<track name>.csv becomes songs/song_<index>_<track name>.h
(see csv_to_song.py), defining the array song_<index>_<track name>. songs.h
includes them all and lists them in tracks[], indexed by <index>.
"""
import glob, os, re, sys
from csv_to_song import read, write

def main(csv_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    tracks = []
    for source in sorted(glob.glob(os.path.join(csv_dir, '*.csv'))):
        m = re.search(r'_(\d+)_([^_].*)\.csv$', os.path.basename(source))
        if not m:
            print(f"skipping {source}: no _<index>_<track name> in its name", file=sys.stderr)
            continue
        index, name = int(m.group(1)), m.group(2)
        array = f"song_{index:02d}_{name.lower()}"
        write(read(source), source, os.path.join(out_dir, array + '.h'), array, '../song.h')
        tracks.append((index, name.replace('_', ' '), array))
        print(os.path.join(out_dir, array + '.h'))
    with open(os.path.join(out_dir, 'songs.h'), 'w') as f:
        f.write("// Generated by script/csv_to_songs.py, do not edit by hand.\n")
        f.write("// all the tracks, in flash: tracks[i] is track i of the MIDI file.\n")
        f.write("#ifndef SONGS_H\n#define SONGS_H\n\n")
        for index, name, array in tracks:
            f.write(f"#include \"{array}.h\"\n")
        f.write("\n#define TRACK(a, name) { a, sizeof(a) / sizeof(a[0]), name }\n\n")
        f.write("const track_t tracks[] = {\n")
        for index, name, array in tracks:
            f.write(f"    [{index:2d}] = TRACK({array}, \"{name}\"),\n")
        f.write("};\n\n#define NUM_TRACKS (sizeof(tracks) / sizeof(tracks[0]))\n\n#endif\n")
    print(os.path.join(out_dir, 'songs.h'))

if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])

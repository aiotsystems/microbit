"""Convert every CSV of a folder into a C song, and write songs.h to pick one.

Usage: python3 csv_to_songs.py reference/ songs/

Each <midi name>_<index>_<track name>.csv becomes songs/song_<index>_<track name>.h
(see csv_to_song.py), defining the array song_<index>_<track name>, padded with
silence to the length of the longest track, so they all last as long. songs.h
includes them all and lists them in tracks[], in the order of ORDER (tracks not
in ORDER come last, in the order of the MIDI file). tracks[i] is what the board
calls track i.
"""
import glob, os, re, sys
from csv_to_song import read, write, DURATION_MAX_MS

# the order of the tracks on the boards, by MIDI track: ORDER[i] is track i
ORDER = [
     4, # Trumpet
     0, # Tremolo Strings
     1, # Trombone
     2, # Brass
     3, # French Horn
     6, # Tuba
     7, # Tuba 2
     8, # Strings
     9, # Strings 2
    10, # Flute Classic
    11, # Piccolo
    12, # Oboe
    13, # Clarinet
    14, # Bassoon
    16, # Concert Harp
    15, # Glock
     5, # Trumpet 2
    17, # Snare
    18, # Timpani D
    19, # Timpani A
    20, # Timpani F
    21, # Cymbals
    22, # Other Percussion
    23, # French Horn Classic
    24, # Trombone Classic
    25, # Trumpet
    26, # Brass
    27, # Violin Classic
]

def main(csv_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    tracks = []
    for source in sorted(glob.glob(os.path.join(csv_dir, '*.csv'))):
        m = re.search(r'_(\d+)_([^_].*)\.csv$', os.path.basename(source))
        if not m:
            print(f"skipping {source}: no _<index>_<track name> in its name", file=sys.stderr)
            continue
        index, name = int(m.group(1)), m.group(2)
        array = f"song_{index:02d}_{name.lower()}"
        tracks.append((index, name.replace('_', ' '), array, source, read(source)))
    # every track ends with its last note: pad them all with silence to the length
    # of the piece, so that the boards loop at the same time and stay in sync
    length = max(sum(d for _, _, d in notes) for *_, notes in tracks)
    for index, name, array, source, notes in tracks:
        silence = length - sum(d for _, _, d in notes)
        while silence > 0:
            notes.append(('silence', 0, min(silence, DURATION_MAX_MS)))
            silence -= DURATION_MAX_MS
        write(notes, source, os.path.join(out_dir, array + '.h'), array, '../song.h')
        print(os.path.join(out_dir, array + '.h'))
    tracks = [t[:3] for t in tracks]
    tracks.sort(key=lambda t: (ORDER.index(t[0]) if t[0] in ORDER else len(ORDER), t[0]))
    with open(os.path.join(out_dir, 'songs.h'), 'w') as f:
        f.write("// Generated by script/csv_to_songs.py, do not edit by hand.\n")
        f.write("// all the tracks, in flash: tracks[i] is track i on the boards (see ORDER in\n")
        f.write("// csv_to_songs.py), the number in the name of each array is its MIDI track.\n")
        f.write("#ifndef SONGS_H\n#define SONGS_H\n\n")
        for index, name, array in tracks:
            f.write(f"#include \"{array}.h\"\n")
        f.write("\n#define TRACK(a, name) { a, sizeof(a) / sizeof(a[0]), name }\n\n")
        f.write("const track_t tracks[] = {\n")
        for i, (index, name, array) in enumerate(tracks):
            f.write(f"    [{i:2d}] = TRACK({array}, \"{name}\"),\n")
        f.write("};\n\n#define NUM_TRACKS (sizeof(tracks) / sizeof(tracks[0]))\n\n#endif\n")
    print(os.path.join(out_dir, 'songs.h'))

if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
